#!/usr/bin/env python3
"""Validate the exported MEPS asset and write docs/DATA_REPORT.md. Exit code 1 on failure."""
import json, math, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from meps_common import DERIVED, ROOT

a = json.loads((DERIVED / "meps_baseline.json").read_text())
fails = []
def check(ok, msg):
    print(("PASS " if ok else "FAIL ") + msg)
    if not ok: fails.append(msg)

def finite(o):
    if isinstance(o, dict): return all(finite(v) for v in o.values())
    if isinstance(o, list): return all(finite(v) for v in o)
    return not (isinstance(o, float) and not math.isfinite(o))

check(finite(a), "no NaN/Inf anywhere")
check(abs(sum(c["share"] for c in a["cells"]) - 1) < 1e-9, "cell shares sum to 1")
check(abs(sum(a["marginals"]["payerShare"].values()) - 1) < 1e-9, "payer shares sum to 1")
check(abs(sum(a["marginals"]["ageShare"].values()) - 1) < 1e-9, "age shares sum to 1")
check(all(v >= 0 for c in a["cells"] for v in c["ratesPerPersonYear"].values()), "all rates >= 0")
check(2.9e8 < a["counts"]["weightedPopulation"] < 3.8e8, "weighted population ~ US civilian noninstitutionalized (339.8M expected)")
for svc, r in a["reconciliation"].items():
    check(r["ratio"] is not None and 0.95 < r["ratio"] < 1.05, f"{svc}: event-file vs person-file weighted counts within 5% (ratio {r['ratio']:.3f})")
mono = True
for svc, s in a["payments"].items():
    for py, d in {**s["byPayer"], "pooled": s["pooled"]}.items():
        for k in ("facilityPaymentCents", "physicianPaymentCents", "facilityOutOfPocketCents"):
            q = d[k]["quantiles"]
            mono &= all(x <= y for x, y in zip(q, q[1:])) and all(isinstance(x, int) and x >= 0 for x in q)
check(mono, "payment quantiles monotone, non-negative integer cents")
check("DUPERSID" not in json.dumps(a).replace("DUPERSID (not exported)", "").replace('"personKey"', ""), "no respondent IDs exported")

rep = ["# Data report (auto-generated by scripts/validate_baseline.py)\n",
       f"Model version `{a['modelVersion']}` · provenance `{a['provenanceKind']}` · {a['counts']['personsPositiveWeight']} persons with PERWT24F>0 · weighted pop {a['counts']['weightedPopulation']:,.0f}\n",
       "## Payer mix (weighted)\n", *[f"- {k}: {v:.1%}" for k, v in a["marginals"]["payerShare"].items()],
       "\n## Age mix (weighted)\n", *[f"- {k}: {v:.1%}" for k, v in a["marginals"]["ageShare"].items()],
       "\n## Events per person-year (weighted)\n", *[f"- {k}: {v:.3f}" for k, v in a["marginals"]["overallRatesPerPersonYear"].items()],
       "\n## Event vs person file reconciliation\n", *[f"- {k}: ratio {v['ratio']:.3f}; facility payments ${v['eventFileWeightedFacilityPaymentUSD']/1e9:.1f}B; physician payments ${v['eventFileWeightedPhysicianPaymentUSD']/1e9:.1f}B; person-file service expenditure ${v['personFileWeightedExpenditureUSD']/1e9:.1f}B" for k, v in a["reconciliation"].items()],
       "\n## Build log\n", *[f"- {l}" for l in a["buildLog"]],
       "\n## Result\n", "ALL CHECKS PASSED" if not fails else "FAILED: " + "; ".join(fails)]
(ROOT / "docs").mkdir(exist_ok=True)
(ROOT / "docs" / "DATA_REPORT.md").write_text("\n".join(rep) + "\n")
sys.exit(1 if fails else 0)
